/**
 * Відділи організації. Фіксований набір значень, який використовується
 * у класі {@link Employee}.
 */
public enum Department {

    /** Відділ інформаційних технологій. */
    IT("ІТ"),

    /** Відділ кадрів. */
    HR("Кадри"),

    /** Фінансовий відділ. */
    FINANCE("Фінанси"),

    /** Відділ продажів. */
    SALES("Продажі"),

    /** Відділ підтримки. */
    SUPPORT("Підтримка");

    private final String title;

    /**
     * Створює значення перерахування з українською назвою.
     *
     * @param title назва відділу для виведення користувачу
     */
    Department(String title) {
        this.title = title;
    }

    /**
     * Повертає назву відділу.
     *
     * @return українська назва відділу
     */
    public String getTitle() {
        return title;
    }

    /**
     * Повертає назву відділу для виведення.
     *
     * @return українська назва відділу
     */
    @Override
    public String toString() {
        return title;
    }
}